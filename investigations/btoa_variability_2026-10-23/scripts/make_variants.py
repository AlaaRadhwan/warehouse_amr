#!/usr/bin/env python3
"""Generate the experiment's launch variants from the CURRENT repo files (nothing in src/ is modified).

Both arms are generated by the same code path from the same sources; the only difference between
their controllers.yaml is the single wheel_separation_multiplier line (asserted below).
Start pose = Station B (spawn pose and AMCL initial pose), from src/amr_missions/config/stations.yaml.

usage: make_variants.py OUT_DIR MULTIPLIER
writes OUT_DIR/{controllers.yaml,simulation.launch.py,bringup.launch.py,variant.json}
"""
import hashlib, json, re, sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[3]
out, mult = Path(sys.argv[1]), sys.argv[2]
out.mkdir(parents=True, exist_ok=True)
float(mult)  # must parse

# 1. controllers.yaml: identical to the repo file except the multiplier value
src_c = (REPO / "src/amr_control/config/controllers.yaml").read_text()
pat = re.compile(r"^(\s*wheel_separation_multiplier:\s*)\S+(.*)$", re.M)
assert len(pat.findall(src_c)) == 1
new_c = pat.sub(lambda m: f"{m.group(1)}{mult}{m.group(2)}", src_c)
(out / "controllers.yaml").write_text(new_c)
chg = [(a, b) for a, b in zip(src_c.splitlines(), new_c.splitlines()) if a != b]
assert len(chg) <= 1, chg

# 2. simulation.launch.py pointing at that controllers file
sim = (REPO / "src/amr_simulation/launch/simulation.launch.py").read_text()
old = '''    controllers_file = PathJoinSubstitution([
        FindPackageShare("amr_control"),
        "config",
        "controllers.yaml",
    ])'''
assert old in sim
(out / "simulation.launch.py").write_text(sim.replace(old, f'    controllers_file = "{out / "controllers.yaml"}"'))

# 3. bringup launch: spawn + AMCL initial pose at Station B, include the generated simulation launch
b = (REPO / "src/amr_bringup/launch/simulation_navigation.launch.py").read_text()
old_home = '''    home_x = float(home["x"])
    home_y = float(home["y"])
    home_yaw = float(home["yaw"])'''
old_inc = '''os.path.join(
                simulation_share,
                "launch",
                "simulation.launch.py",
            )'''
assert old_home in b and old_inc in b
st = yaml.safe_load((REPO / "src/amr_missions/config/stations.yaml").read_text())
st = st.get("stations", st)
B = st["station_b"]
new_home = f'    home_x, home_y, home_yaw = {float(B["x"])!r}, {float(B["y"])!r}, {float(B["yaw"])!r}  # EXPERIMENT: start at station B'
b = b.replace(old_home, new_home).replace(old_inc, f'"{out / "simulation.launch.py"}"')
(out / "bringup.launch.py").write_text(b)

sha = lambda p: hashlib.sha256((out / p).read_bytes()).hexdigest()[:16]
(out / "variant.json").write_text(json.dumps({
    "multiplier": float(mult), "start_pose_station_b": B,
    "controllers_diff": [{"repo": a.strip(), "variant": c.strip()} for a, c in chg],
    "sha256_16": {n: sha(n) for n in ("controllers.yaml", "simulation.launch.py", "bringup.launch.py")}}, indent=2))
print(out / "bringup.launch.py")
